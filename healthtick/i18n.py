"""Localized strings (Chinese / English).

A tiny lookup object keeps call sites close to the Swift original (`L.foo`).
The active language can be switched at runtime by assigning `L.lang`.
"""

from __future__ import annotations

import os
from enum import Enum


class AppLanguage(str, Enum):
    SYSTEM = "system"
    ZH = "zh"
    EN = "en"

    @property
    def resolved(self) -> "AppLanguage":
        if self is not AppLanguage.SYSTEM:
            return self
        value = (
            os.environ.get("LC_ALL")
            or os.environ.get("LC_MESSAGES")
            or os.environ.get("LANG")
            or "en"
        )
        return AppLanguage.ZH if value.lower().startswith("zh") else AppLanguage.EN

    @property
    def display_name(self) -> str:
        if self is AppLanguage.SYSTEM:
            return "跟随系统" if self.resolved is AppLanguage.ZH else "System"
        return "中文" if self is AppLanguage.ZH else "English"


